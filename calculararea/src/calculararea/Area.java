public class Area {
    
    public static int calculararea(int altura, int largura){
        return altura*largura;
    }
    
    public static double calculararea(double altura, double largura){
        return altura*largura;
    }
    
    public static int calculararea(int largura){
        return largura*largura;
    }
    
    
    
}
